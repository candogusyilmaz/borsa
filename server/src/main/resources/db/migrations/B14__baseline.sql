CREATE TABLE portfolio.position_daily_snapshots (
    id bigint GENERATED BY DEFAULT AS IDENTITY (SEQUENCE NAME portfolio.holding_daily_snapshots_id_seq),
    average_price numeric(20,8) NOT NULL,
    created_at timestamp(6) with time zone NOT NULL,
    daily_profit numeric(15,2) GENERATED ALWAYS AS ((((quantity)::numeric * market_price) - ((quantity)::numeric * previous_market_price))) STORED NOT NULL,
    daily_profit_percentage numeric(5,2) GENERATED ALWAYS AS (
        CASE
            WHEN (previous_market_price > (0)::numeric)
                THEN (((((quantity)::numeric * market_price) - ((quantity)::numeric * previous_market_price)) / ((quantity)::numeric * previous_market_price)) * (100)::numeric)
            ELSE NULL::numeric
        END
    ) STORED NOT NULL,
    market_price numeric(20,8) NOT NULL,
    market_value numeric(15,2) GENERATED ALWAYS AS (((quantity)::numeric * market_price)) STORED NOT NULL,
    portfolio_weight_percentage numeric(5,2) NOT NULL,
    previous_market_price numeric(20,8) NOT NULL,
    quantity integer NOT NULL,
    total_commission numeric(20,8),
    total_cost numeric(15,2) GENERATED ALWAYS AS (((quantity)::numeric * average_price)) STORED NOT NULL,
    total_profit numeric(15,2) GENERATED ALWAYS AS ((((quantity)::numeric * market_price) - ((quantity)::numeric * average_price))) STORED NOT NULL,
    total_profit_percentage numeric(5,2) GENERATED ALWAYS AS (
        CASE
            WHEN (((quantity)::numeric * average_price) > (0)::numeric)
                THEN (((((quantity)::numeric * market_price) - ((quantity)::numeric * average_price)) / ((quantity)::numeric * average_price)) * (100)::numeric)
            ELSE NULL::numeric
        END
    ) STORED NOT NULL,
